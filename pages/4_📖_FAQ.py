def faq(label, what, marker, how, stats=None, caution=None):
    with st.expander(label):
        st.markdown(f"**Что показывает:** {what}")
        st.markdown(f"**Маркер:** {marker}")
        st.markdown(f"**Как использовать:** {how}")
        if stats: st.markdown(f"**Статистика:** {stats}")
        if caution: st.warning(caution)

st.markdown("### 🔘 Описание кнопок")

faq("👥 Кластера Ф/Ю",
    "Сырой факт от биржи: где за 5 минут физлица (Ф) и юрлица (Ю) заметно набрали позицию.",
    "Стрелки/кружки у свечи (1× отступ).",
    "Смотреть, кто активен и в какую сторону. Это факт «после события», сам по себе не сигнал входа.")

